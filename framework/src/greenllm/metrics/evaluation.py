import requests
import json
import re
import time
import os

API_KEY = os.getenv("API_KEY")

if API_KEY is None:
    API_KEY_FILE=os.environ.get("API_KEY_FILE","../api.key")
    with open(API_KEY_FILE, "r") as f:
        API_KEY = f.read().strip()

API_URL = os.getenv("API_URL","https://openrouter.ai/api/v1/chat/completions")
SITE_URL = os.getenv("SITE_URL","https://tu-sitio.com")
SITE_NAME = os.getenv("SITE_NAME","Mi Sitio")

def evaluar_modelos(prompts, disciplinas, resultados, seed, model="deepseek/deepseek-chat-v3.1:free"):
    """
    Evaluates a list of results generated by language models using OpenRouter.
    Returns a list of scores (float between 0 and 10, never None).
    """

    puntuaciones = []

    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "HTTP-Referer": SITE_URL,
        "X-Title": SITE_NAME,
        "Content-Type": "application/json"
    }

    for i, (prompt_text, disciplina_text, resultado_text) in enumerate(zip(prompts, disciplinas, resultados), start=1):

        time.sleep(1)

        prompt = f"""
        You are an expert evaluator of language model outputs.

        Your task is to assign a single decimal score between 0 and 10 
        for the overall quality of the following model-generated result.

        The score should be based on:
        - Clarity and coherence of the response
        - Relevance to the prompt
        - Accuracy or factual correctness (if applicable)
        - Appropriateness to the context of the discipline: {disciplina_text}
        - Ignore any extra commentary in the response; focus only on whether the answer is correct or relevant.

        Return **only** the number (e.g., 7.8). 
        Do not include any extra text, labels, or explanations.
        If there is no answer, return 0.0.

        ---
        Original prompt:
        {prompt_text}

        Response to evaluate:
        {resultado_text}
        ---
        """

        data = {
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "seed": seed
        }

        try:
            response = requests.post(API_URL, headers=headers, data=json.dumps(data), timeout=30)

            if response.status_code == 200:
                result = response.json()
                contenido = result.get("choices", [{}])[0].get("message", {}).get("content", "").strip()


                # Clean possible tags or extra characters
                contenido_limpio = re.sub(r"<.*?>", "", contenido, flags=re.DOTALL).strip()
                match = re.search(r"\b\d+(\.\d+)?\b", contenido_limpio)

                if match:
                    puntuacion = float(match.group(0))
                    puntuacion = max(0.0, min(10.0, puntuacion))
                else:
                    print(f"[Warning] No se pudo extraer un valor numérico de la respuesta para el prompt {i}. Valor asignado: 0.0")
                    puntuacion = 0.0

            else:
                print(f"[HTTP Error {response.status_code}] {response.text}")
                puntuacion = 0.0

        except Exception as e:
            print(f"[Error] Procesando prompt {i}: {e}")
            puntuacion = 0.0

        puntuaciones.append(puntuacion)

    return puntuaciones


